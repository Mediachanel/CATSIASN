import { test, expect } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
const email = `e2e-${Date.now()}@example.test`;
const password = "correct horse battery staple";
const db = new PrismaClient();
test.afterAll(async () => { await db.user.deleteMany({ where: { email } }); await db.$disconnect(); });
test("participant registers, signs in and signs out", async ({ page }) => {
  await page.goto("/dashboard");
  await expect(page).toHaveURL(/\/login/);
  await page.goto("/register");
  await page.getByLabel("Nama").fill("Peserta Uji");
  await page.getByLabel("Email").fill(email);
  await page.getByLabel("Kata sandi").fill(password);
  await page.getByRole("button", { name: "Buat akun" }).click();
  await expect(page).toHaveURL(/\/login\?registered=1/);
  const user = await db.user.findUniqueOrThrow({ where: { email } });
  expect(user.passwordHash).toMatch(/^\$argon2id\$/);
  expect(user.passwordHash).not.toContain(password);
  expect(user.role).toBe("PARTICIPANT");
  await page.getByLabel("Email").fill(email);
  await page.getByLabel("Kata sandi").fill("wrong password");
  await page.getByRole("button", { name: "Masuk" }).click();
  await expect(page.getByRole("alert")).toBeVisible();
  await page.getByLabel("Email").fill(email);
  await page.getByLabel("Kata sandi").fill(password);
  await page.getByRole("button", { name: "Masuk" }).click();
  await expect(page).toHaveURL(/\/dashboard/);
  await expect(page.getByRole("heading", { name: "Halo, Peserta Uji." })).toBeVisible();
  await page.getByRole("link", { name: "Lihat tryout tersedia" }).click();
  await expect(page.getByRole("heading", { name: "Uji kesiapanmu dengan simulasi penuh." })).toBeVisible();
  await page.getByRole("button", { name: "Mulai simulasi" }).click();
  await expect(page).toHaveURL(/\/exam\//);
  await expect(page.getByRole("heading", { name: "Navigasi soal" })).toBeVisible();
  await page.getByRole("radio").first().check();
  await expect(page.getByText("Status jawaban: tersimpan")).toBeVisible();
  await page.getByRole("button", { name: "Lewati soal" }).click();
  await expect(page.getByText("Soal 2 dari 110")).toBeVisible();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Akhiri simulasi" }).click();
  await expect(page).toHaveURL(/\/results\//);
  await expect(page.getByRole("heading", { name: "Hasil latihan tersimpan." })).toBeVisible();
  await page.goto("/dashboard");
  await page.getByRole("button", { name: "Keluar" }).click();
  await expect(page).toHaveURL(/\/login/);
  await page.goto("/dashboard");
  await expect(page).toHaveURL(/\/login/);
});
